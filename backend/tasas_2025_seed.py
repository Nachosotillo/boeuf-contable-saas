async def sembrar_tasas_2025(db, sobrescribir: bool = False) -> dict:
    """Carga la serie 2025 en tasa_cambio_bcv. Idempotente.

    - sobrescribir=False: solo inserta fechas que falten (respeta overrides manuales).
    - sobrescribir=True : re-sincroniza tasa_usd y fuente desde el consolidado.
    """
    res = await db.execute(select(TasaCambioBcv))
    existentes = {r.fecha: r for r in res.scalars().all()}
    nuevas = actualizadas = 0
    for fecha_iso, tasa in TASAS_2025:
        f = date.fromisoformat(fecha_iso)
        val = Decimal(tasa)
        if f in existentes:
            if sobrescribir:
                rec = existentes[f]
                rec.tasa_usd = val
                rec.fuente = FUENTE
                actualizadas += 1
        else:
            db.add(TasaCambioBcv(fecha=f, tasa_usd=val, fuente=FUENTE))
            nuevas += 1
    await db.flush()
    return {"nuevas": nuevas, "actualizadas": actualizadas, "total_consolidado": len(TASAS_2025)}

